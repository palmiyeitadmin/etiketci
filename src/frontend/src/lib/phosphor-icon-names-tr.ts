const DIRECTION_ADJECTIVE: Record<string, string> = { Up: "yukarı", Down: "aşağı", Left: "sol", Right: "sağ" };
const DIRECTION_TOWARD: Record<string, string> = { Up: "yukarı", Down: "aşağı", Left: "sola", Right: "sağa" };
const DIAGONALS: Record<string, string> = {
  "Up Right": "sağ üst", "Right Up": "sağ üst", "Up Left": "sol üst", "Left Up": "sol üst",
  "Down Right": "sağ alt", "Right Down": "sağ alt", "Down Left": "sol alt", "Left Down": "sol alt",
  "Up Down": "yukarı-aşağı", "Down Up": "aşağı-yukarı", "Left Right": "sol-sağ",
};

/** Arrow describers; ones that make the arrow turn read best as "(aşağı → sola)". */
const ARROW_STYLES: Record<string, { word: string; turns?: boolean }> = {
  Fat: { word: "kalın" },
  Line: { word: "çizgili" },
  Lines: { word: "çok çizgili" },
  Double: { word: "çift" },
  Arc: { word: "kavisli" },
  Bend: { word: "kıvrık", turns: true },
  Elbow: { word: "dirsekli", turns: true },
  U: { word: "U dönüşlü", turns: true },
};

function splitKey(key: string) {
  return key.match(/[A-Z][a-z0-9]*/g) ?? [key];
}

function capitalize(value: string) {
  return value.charAt(0).toLocaleUpperCase("tr") + value.slice(1);
}

/** Turkish "with" suffix by vowel harmony: "artı" → "artılı", "kilit" → "kilitli". */
function withSuffix(noun: string) {
  const vowels = noun.toLocaleLowerCase("tr").match(/[aıeiouöü]/g);
  const last = vowels?.[vowels.length - 1] ?? "e";
  const suffix = { a: "lı", ı: "lı", e: "li", i: "li", o: "lu", u: "lu", ö: "lü", ü: "lü" }[last] ?? "li";
  return noun + suffix;
}

function noun(word: Word) {
  return typeof word === "string" ? word : word[0];
}

function describer(word: Word) {
  return typeof word === "string" ? withSuffix(word) : word[1];
}

function withQualifiers(name: string, qualifiers: string[]) {
  return qualifiers.length > 0 ? `${name} (${qualifiers.join(", ")})` : name;
}

/** Longest dictionary phrase starting at `start`. */
function matchWord(tokens: string[], start: number): { word: Word; length: number } | null {
  for (let length = Math.min(3, tokens.length - start); length >= 1; length -= 1) {
    const phrase = tokens.slice(start, start + length).join(" ");
    if (phrase in WORDS) {
      return { word: WORDS[phrase], length };
    }
  }
  return null;
}

function logoName(tokens: string[]) {
  const at = tokens.indexOf("Logo");
  const brandKey = tokens.slice(0, at).join(" ");
  const brand = BRANDS[brandKey] ?? brandKey;
  const qualifiers = tokens.slice(at + 1).map((token) => QUALIFIERS[token] ?? token);
  return withQualifiers(`${brand} logosu`, qualifiers);
}

function arrowName(tokens: string[]) {
  const nounText = tokens[0] === "Caret" ? "ok ucu" : "ok";
  let container: string | null = null;
  const styles: { word: string; turns?: boolean }[] = [];
  const directions: string[] = [];
  for (const token of tokens.slice(1)) {
    if (token in DIRECTION_ADJECTIVE) directions.push(token);
    else if (token in ARROW_STYLES) styles.push(ARROW_STYLES[token]);
    else if (token in CONTAINERS) container = CONTAINERS[token];
    else return null;
  }

  const turns = styles.some((style) => style.turns);
  const describers = styles.map((style) => style.word).reverse();
  const prefix = container ? [`${container} içinde`] : [];
  if (turns && directions.length === 2) {
    const route = `${DIRECTION_TOWARD[directions[0]]} → ${DIRECTION_TOWARD[directions[1]]}`;
    return `${[...prefix, ...describers, nounText].join(" ")} (${route})`;
  }

  const direction = directions.length === 2
    ? DIAGONALS[directions.join(" ")]
    : directions.length === 1 ? DIRECTION_ADJECTIVE[directions[0]] : undefined;
  if (directions.length > 0 && !direction) return null;
  return [...prefix, ...describers, ...(direction ? [direction] : []), nounText].join(" ");
}

function numberName(tokens: string[]) {
  const digit = NUMBERS[tokens[tokens.length - 1]];
  if (!digit) return null;
  if (tokens.length === 2) return `${digit} rakamı`;
  const container = CONTAINERS[tokens[1]];
  return container && tokens.length === 3 ? `${container} içinde ${digit}` : null;
}

function fileName(tokens: string[]) {
  const rest = tokens.slice(1).join(" ");
  const format = FILE_FORMATS[rest];
  return format ? `${format} dosyası` : null;
}

function composedName(tokens: string[]) {
  const head = matchWord(tokens, 0);
  if (!head) return null;

  let container: string | null = null;
  const describers: string[] = [];
  const qualifiers: string[] = [];
  let index = head.length;
  while (index < tokens.length) {
    const token = tokens[index];
    if (token in QUALIFIERS) {
      qualifiers.push(QUALIFIERS[token]);
      index += 1;
      continue;
    }
    if (token in CONTAINERS && !container) {
      container = CONTAINERS[token];
      index += 1;
      continue;
    }
    if (token in NUMBER_WORDS) {
      describers.push(NUMBER_WORDS[token]);
      index += 1;
      continue;
    }
    const match = matchWord(tokens, index);
    if (!match) return null;
    describers.push(describer(match.word));
    index += match.length;
  }

  // Turkish puts the describers before the noun, the outermost first: "Book Open Text" → "Metinli açık kitap".
  const words = [...(container ? [`${container} içinde`] : []), ...describers.reverse(), noun(head.word)];
  return withQualifiers(words.join(" "), qualifiers);
}

type NameSource = "override" | "composed" | "fallback";

function buildName(key: string): { name: string; source: NameSource } {
  const override = OVERRIDES[key];
  if (override) return { name: override, source: "override" };

  const tokens = splitKey(key);
  const composed =
    (tokens.includes("Logo") ? logoName(tokens) : null) ??
    (tokens[0] === "Arrow" || tokens[0] === "Caret" ? arrowName(tokens) : null) ??
    (tokens[0] === "Number" ? numberName(tokens) : null) ??
    (tokens[0] === "Dice" && tokens.length === 2 && NUMBERS[tokens[1]] ? `Zar (${NUMBERS[tokens[1]]})` : null) ??
    (tokens[0] === "File" ? fileName(tokens) : null) ??
    composedName(tokens);
  // The fallback keeps the picker usable for icons added to the manifest later; tests keep it unused.
  return composed ? { name: capitalize(composed), source: "composed" } : { name: tokens.join(" "), source: "fallback" };
}

const cache = new Map<string, string>();

/** Natural Turkish name for a Phosphor icon key, e.g. "CloudRain" → "Yağmurlu bulut". */
export function turkishIconName(key: string): string {
  let name = cache.get(key);
  if (name === undefined) {
    name = buildName(key).name;
    cache.set(key, name);
  }
  return name;
}

/** Where a key's name comes from: a hand-written override, the dictionary, or the untranslated fallback. */
export function turkishIconNameSource(key: string): NameSource {
  return buildName(key).source;
}
