/** "PrintIntentUserPrinted" → "Print intent user printed", for codes the module does not know yet. */
export function humanizeCode(code: string) {
    const words = code.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/[_-]+/g, " ").trim().toLowerCase();
    return words.charAt(0).toUpperCase() + words.slice(1);
}
